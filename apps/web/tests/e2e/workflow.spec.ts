import { test, expect } from "@playwright/test";
import { demoDescription } from "../fixtures";

test("full founder workflow: profile, map, evidence, confirmation, and approved Stripe impact", async ({ page, context, browser }, testInfo) => {
  const errors: string[] = []; page.on("pageerror", (error) => errors.push(error.message));
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.goto("/"); await expect(page.getByRole("heading", { name: "What are you building?" })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("landing-desktop.png"), fullPage: true });
  await page.getByLabel("Your project", { exact: true }).fill(demoDescription);
  await page.getByRole("button", { name: "Find my blind spots" }).click();
  await page.getByRole("button", { name: "Start the questions" }).click();
  for (let i = 0; i < 5; i++) {
    await expect(page.getByText(`Question ${i + 1} of up to 5`)).toBeVisible();
    await page.getByRole("button", { name: i === 1 ? "Skip" : "I don’t know", exact: true }).click();
  }
  await expect(page.getByRole("heading", { name: "Does this sound right?" })).toBeVisible();
  await expect(page.getByLabel("Provenance for Data handled", { exact: true })).toHaveValue("unknown");
  await page.getByRole("button", { name: "Approve profile & build checkpoints" }).click();
  await expect(page.getByRole("heading", { name: "Your next steps" })).toBeVisible();
  await expect(page.getByText("0 of 3", { exact: true })).toBeVisible();
  await page.getByRole("navigation", { name: "Workspace", exact: true }).getByRole("button", { name: "Readiness map" }).click();
  await expect(page.getByRole("button", { name: /Security & Privacy/ })).toHaveAttribute("aria-expanded", "false");
  await expect(page.getByText("Not assessed yet")).toBeVisible();
  await page.getByRole("button", { name: /Security & Privacy/ }).click();
  await page.getByRole("button", { name: /Checkpoint: Have your builder/ }).click();
  await page.getByRole("button", { name: "Generate engineering prompt", exact: true }).click();
  await page.getByRole("button", { name: "Copy engineering prompt", exact: true }).click();
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toContain("Inspect the existing Lovable");
  await page.getByLabel("Add evidence", { exact: true }).fill("Codex says done. No relevant test output was supplied.");
  await page.getByLabel("Source", { exact: true }).fill("Coding-agent report");
  await page.getByRole("button", { name: "Save evidence", exact: true }).click();
  await page.getByRole("button", { name: "Review this evidence", exact: true }).click();
  await expect(page.getByText("unsupported", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Work status", { exact: true })).toHaveValue("evidence_reviewed");
  await page.getByLabel("Work status", { exact: true }).selectOption("founder_confirmed");
  await page.getByRole("checkbox").check(); await page.getByRole("button", { name: "Save progress" }).click();
  await expect(page.getByLabel("Work status", { exact: true })).toHaveValue("founder_confirmed");
  await page.reload(); await expect(page.getByLabel("Work status", { exact: true })).toHaveValue("founder_confirmed");
  await page.getByRole("navigation", { name: "Workspace", exact: true }).getByRole("button", { name: "Checklist", exact: true }).click();
  await expect(page.getByText("1 of 3", { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("dashboard-desktop.png"), fullPage: true });
  const workspaceUrl = page.url();
  await page.getByRole("button", { name: "New conversation", exact: true }).click();
  await page.getByLabel("Ask your advisor").fill("I just added Stripe subscriptions.");
  await page.getByRole("button", { name: "Send message" }).click();
  await expect(page.getByText("3 updates to review", { exact: true })).toBeVisible();
  await page.getByRole("article", { name: "Add Verify Stripe subscription events" }).getByRole("button", { name: "Approve", exact: true }).click();
  await page.getByRole("article", { name: "Update Stack & integrations" }).getByRole("button", { name: "Approve", exact: true }).click();
  await page.getByRole("article", { name: "Reopen ai spend limits" }).getByRole("button", { name: "Approve", exact: true }).click();
  await page.getByRole("navigation", { name: "Workspace", exact: true }).getByRole("button", { name: "Checklist", exact: true }).click();
  await expect(page.getByText("1 of 4", { exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Verify Stripe subscription events" }).first()).toBeVisible();
  await page.getByRole("button", { name: "Readiness map", exact: true }).click();
  await page.getByRole("button", { name: /^Reliability & Operations/ }).click();
  await expect(page.getByRole("button", { name: /Risk P0 · Critical Verify Stripe subscription events/ })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("map-desktop.png"), fullPage: true });
  const outsider = await browser.newContext(); const outsiderPage = await outsider.newPage(); await outsiderPage.goto(workspaceUrl);
  await expect(outsiderPage.getByRole("heading", { name: "We couldn’t open this workspace." })).toBeVisible(); await outsider.close(); expect(errors).toEqual([]);
});

test("mobile early finish, profile and conversation navigation without overflow", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 375, height: 844 }); await page.goto("/");
  await page.getByRole("button", { name: "Website outages", exact: true }).click();
  await page.screenshot({ path: testInfo.outputPath("landing-mobile.png"), fullPage: true });
  await page.getByRole("button", { name: "Find my blind spots" }).click();
  await page.getByRole("button", { name: "Review profile from what I’ve shared" }).click();
  await page.getByRole("button", { name: "Approve profile & build checkpoints" }).click();
  await expect(page.getByRole("heading", { name: "Your next steps" })).toBeVisible();
  await page.getByRole("button", { name: "Open navigation" }).click();
  await page.getByRole("button", { name: "Getting to know your product" }).click();
  await expect(page.getByRole("heading", { name: "Getting to know your product" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Open navigation" })).toHaveAttribute("aria-expanded", "false");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("history-mobile.png"), fullPage: true });
});
